public class Retangulo {
    private double base;
    private double altura;

    // constructor x getters
    public Retangulo() {
        this.base = 0;
        this.altura = 0;
    }
    public Retangulo(double base, double altura) {
        this.base = base;
        this.altura = altura;
    }

    public double getBase() { return this.base; }
    public double getAltura() { return this.altura; }

}
